-- role ของแอป: ไม่มี BYPASSRLS (T-05) — migration รันด้วย owner (tms), แอปรันด้วย tms_app
CREATE ROLE tms_app LOGIN PASSWORD 'tms_app' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
GRANT CONNECT ON DATABASE tms TO tms_app;
GRANT USAGE ON SCHEMA public TO tms_app;
ALTER DEFAULT PRIVILEGES FOR ROLE tms IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO tms_app;
ALTER DEFAULT PRIVILEGES FOR ROLE tms IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO tms_app;
-- role สำหรับงาน platform (admin portal, job ข้าม tenant) — แยกจาก tms_app
CREATE ROLE tms_platform LOGIN PASSWORD 'tms_platform' NOSUPERUSER NOCREATEDB NOCREATEROLE BYPASSRLS;
GRANT CONNECT ON DATABASE tms TO tms_platform;
GRANT USAGE ON SCHEMA public TO tms_platform;
ALTER DEFAULT PRIVILEGES FOR ROLE tms IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO tms_platform;
ALTER DEFAULT PRIVILEGES FOR ROLE tms IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO tms_platform;
