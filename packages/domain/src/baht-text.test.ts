import { describe, expect, it } from 'vitest';
import { bahtText } from './baht-text';
import { satangFromDecimal } from './money';

const t = (v: string) => bahtText(satangFromDecimal(v));

describe('bahtText (spec/05 §16 BIL-193)', () => {
  it('ตัวอย่างใน spec', () => {
    expect(t('11070.00')).toBe('หนึ่งหมื่นหนึ่งพันเจ็ดสิบบาทถ้วน');
    expect(t('21.50')).toBe('ยี่สิบเอ็ดบาทห้าสิบสตางค์');
    expect(t('1000001.00')).toBe('หนึ่งล้านเอ็ดบาทถ้วน');
    expect(t('25000.00')).toBe('สองหมื่นห้าพันบาทถ้วน');
  });

  it('ต้นแบบ TMS Print', () => {
    expect(t('25744.50')).toBe('สองหมื่นห้าพันเจ็ดร้อยสี่สิบสี่บาทห้าสิบสตางค์');
    expect(t('59740.00')).toBe('ห้าหมื่นเก้าพันเจ็ดร้อยสี่สิบบาทถ้วน');
  });

  it('กรณีขอบ: หนึ่ง/เอ็ด/สิบ/ยี่สิบ/ศูนย์/สตางค์อย่างเดียว/หลายล้าน/ติดลบ', () => {
    expect(t('1.00')).toBe('หนึ่งบาทถ้วน');
    expect(t('10.00')).toBe('สิบบาทถ้วน');
    expect(t('11.00')).toBe('สิบเอ็ดบาทถ้วน');
    expect(t('20.00')).toBe('ยี่สิบบาทถ้วน');
    expect(t('101.00')).toBe('หนึ่งร้อยเอ็ดบาทถ้วน');
    expect(t('0.00')).toBe('ศูนย์บาทถ้วน');
    expect(t('0.01')).toBe('หนึ่งสตางค์');
    expect(t('0.75')).toBe('เจ็ดสิบห้าสตางค์');
    expect(t('1000000.00')).toBe('หนึ่งล้านบาทถ้วน');
    expect(t('21000000.00')).toBe('ยี่สิบเอ็ดล้านบาทถ้วน');
    expect(t('1000000000000.00')).toBe('หนึ่งล้านล้านบาทถ้วน');
    expect(t('2011011.11')).toBe('สองล้านหนึ่งหมื่นหนึ่งพันสิบเอ็ดบาทสิบเอ็ดสตางค์');
    expect(t('-5.00')).toBe('ลบห้าบาทถ้วน');
  });
});
